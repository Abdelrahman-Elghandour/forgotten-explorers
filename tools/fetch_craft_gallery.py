"""Bundle a few real NASA photographs per craft so the stage never depends on the network.

The NASA Image and Video Library is searched per craft, the best four distinct photographs are
downloaded at `~orig` (falling back to `~large`/`~thumb`), downscaled for the web, and written to
`images/craft/`. `src/data/craft-gallery.js` then lists them for the media stage. When the API is
reachable the stage still appends live results and mission footage after these bundled slides.
"""
import json
import urllib.parse
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "images" / "craft"
OUT.mkdir(parents=True, exist_ok=True)
SEARCH = "https://images-api.nasa.gov/search"
CRAFTS = {
    "opp": ["Opportunity rover Mars", "Mars Exploration Rover Opportunity"],
    "spi": ["Spirit rover Mars", "Mars Exploration Rover Spirit"],
    "lun": ["Lunokhod 1", "Luna 17", "Lunokhod rover"],
}
PER_CRAFT = 4
MAX_W = 1600


def get(url, binary=False):
    req = urllib.request.Request(url, headers={"User-Agent": "forgotten-explorers/1.0"})
    with urllib.request.urlopen(req, timeout=45) as r:
        data = r.read()
    return data if binary else json.loads(data)


def candidates(item):
    href = (item.get("links") or [{}])[0].get("href")
    if not href:
        return []
    base = href.replace("~thumb", "").replace("~small", "").replace("~medium", "").replace("~large", "")
    stem = base.rsplit(".", 1)[0]
    return [stem + "~orig.jpg", stem + "~large.jpg", stem + "~thumb.jpg"]


def main():
    gallery = {}
    for cid, queries in CRAFTS.items():
        items, seen_queries = [], set()
        for query in queries:
            if query in seen_queries:
                continue
            seen_queries.add(query)
            url = f"{SEARCH}?q={urllib.parse.quote(query)}&media_type=image&page_size=20"
            try:
                items.extend(get(url)["collection"]["items"])
            except Exception as exc:
                print(f"  {cid}: query failed ({query}) {exc}")
        picked, seen = [], set()
        for it in items:
            meta = (it.get("data") or [{}])[0]
            nasa_id = meta.get("nasa_id")
            if not nasa_id or nasa_id in seen or meta.get("media_type") != "image":
                continue
            saved = None
            for cand in candidates(it):
                try:
                    raw = get(cand, binary=True)
                except Exception:
                    continue
                if len(raw) < 20000:
                    continue
                tmp = OUT / f"{cid}-{len(picked) + 1}.jpg"
                tmp.write_bytes(raw)
                try:
                    im = Image.open(tmp)
                    im = im.convert("RGB")
                    if im.width > MAX_W:
                        im = im.resize((MAX_W, round(im.height * MAX_W / im.width)), Image.Resampling.LANCZOS)
                    im.save(tmp, "JPEG", quality=84, optimize=True, progressive=True)
                    saved = tmp
                except Exception:
                    tmp.unlink(missing_ok=True)
                    continue
                break
            if not saved:
                continue
            seen.add(nasa_id)
            picked.append({
                "src": f"./images/craft/{saved.name}",
                "title": (meta.get("title") or "NASA").strip(),
                "nasaId": nasa_id,
            })
            if len(picked) >= PER_CRAFT:
                break
        gallery[cid] = picked
        print(f"{cid}: {len(picked)} photographs", [p["nasaId"] for p in picked])

    body = json.dumps(gallery, ensure_ascii=False, indent=2)
    (ROOT / "src" / "data" / "craft-gallery.js").write_text(
        "/* Bundled NASA photographs per craft, generated by tools/fetch_craft_gallery.py.\n"
        "   Keeps the media stage populated when the image API is unreachable. */\n"
        f"window.CRAFT_GALLERY = {body};\n",
        encoding="utf-8",
    )
    total = sum(len(v) for v in gallery.values())
    print(f"wrote {total} bundled slides")


if __name__ == "__main__":
    main()
