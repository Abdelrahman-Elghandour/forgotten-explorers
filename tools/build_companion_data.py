"""Derive the 3D companion's data from the narration itself.

* `src/data/mission-sentences.js` — sentence windows for the live English transcript,
  built by folding the measured phrase cues into the sentences of `enDiary`.
* `src/data/voice-envelopes.js` — a 20 Hz RMS envelope of each recording, used to drive
  the robot's LED pulses and mast motion from the voice instead of a decorative loop.
"""
from pathlib import Path
import json
import re
import subprocess
import sys

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RATE = 16000
HOP = 0.05


def load(script, global_name):
    source = (ROOT / script).read_text()
    out = subprocess.run(
        ['node', '-e', f'const vm=require("vm");const c={{window:{{}}}};vm.runInNewContext({json.dumps(source)},c);console.log(JSON.stringify(c.window.{global_name}))'],
        capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def norm(text):
    return re.sub(r'[^a-z0-9]+', ' ', text.lower()).strip()


def sentences_of(text):
    parts = re.split(r'(?<=[.!?])\s+', text.strip())
    return [p.strip() for p in parts if p.strip()]


def fold_cues(transcript, cues):
    """Group phrase cues into the sentences they belong to."""
    rows = []
    i = 0
    buffer = ''
    start = None
    for cue in cues:
        if start is None:
            start = cue['start']
        buffer = (buffer + ' ' + cue['text']).strip()
        if i < len(transcript) and norm(buffer).startswith(norm(transcript[i])):
            rows.append({'start': round(start, 3), 'end': round(cue['end'], 3), 'text': transcript[i]})
            i += 1
            buffer = ''
            start = None
    if buffer:
        raise SystemExit(f'unfolded narration text remains: {buffer!r}')
    if i != len(transcript):
        raise SystemExit(f'{len(transcript) - i} sentences never matched their cues')
    return rows


def envelope(path):
    raw = subprocess.check_output(['ffmpeg', '-v', 'error', '-i', str(path), '-f', 'f32le', '-ar', str(RATE), '-ac', '1', '-'])
    audio = np.frombuffer(raw, dtype=np.float32)
    step = int(RATE * HOP)
    frames = len(audio) // step
    rms = np.array([float(np.sqrt(np.mean(np.square(audio[i * step:(i + 1) * step])))) for i in range(frames)])
    peak = np.percentile(rms, 97) or rms.max() or 1.0
    shaped = np.clip(rms / peak, 0, 1) ** 0.75
    # 3-frame smoothing keeps the LEDs from flickering between syllables
    smooth = np.convolve(shaped, np.ones(3) / 3, mode='same')
    return [round(float(v), 2) for v in smooth], round(len(audio) / RATE, 3)


def main():
    transcripts = load('src/data/voice-transcripts.js', 'VOICE_TRANSCRIPTS')
    cues = load('src/data/mission-caption-cues.js', 'MISSION_CAPTION_CUES')

    sentence_rows = {}
    for key in ('opp', 'spi', 'lun'):
        sentence_rows[key] = fold_cues(sentences_of(transcripts[key]), cues[key])

    js = ['/* Generated by tools/build_companion_data.py — sentence windows for the live transcript. */',
          '(function (global) {', '  "use strict";',
          '  global.MISSION_SENTENCES = ' + json.dumps(sentence_rows, ensure_ascii=False, indent=2) + ';',
          '})(window);', '']
    (ROOT / 'src' / 'data' / 'mission-sentences.js').write_text('\n'.join(js), encoding='utf-8')

    envelopes, lengths = {}, {}
    for key in ('opp', 'spi', 'lun'):
        envelopes[key], lengths[key] = envelope(ROOT / 'audio' / f'{key}.mp3')

    js = ['/* Generated by tools/build_companion_data.py — 20 Hz RMS envelope of each narration. */',
          '(function (global) {', '  "use strict";',
          '  global.VOICE_ENVELOPES = {',
          '    rate: ' + str(int(1 / HOP)) + ',',
          '    lengths: ' + json.dumps(lengths) + ',']
    for key, values in envelopes.items():
        js.append(f'    {key}: [' + ','.join(str(v) for v in values) + '],')
    js += ['  };', '})(window);', '']
    (ROOT / 'src' / 'data' / 'voice-envelopes.js').write_text('\n'.join(js), encoding='utf-8')

    for key, rows in sentence_rows.items():
        print(f'{key}: {len(rows)} sentences, last ends {rows[-1]["end"]}s, envelope {lengths[key]}s')
    print('companion data written')


if __name__ == '__main__':
    sys.exit(main())
